import json
import logging
import threading
import base64
from cryptography.hazmat.primitives import serialization
from py_vapid import Vapid
from pywebpush import webpush, WebPushException
from django.conf import settings
from django.utils import timezone
from core.models import PlatformSetting, PushSubscription

logger = logging.getLogger(__name__)


def get_or_create_vapid_keys():
    """
    Retrieves the VAPID keypair from PlatformSetting singleton.
    If not yet generated, atomically creates and saves a new NIST P-256 keypair.
    """
    platform_settings = PlatformSetting.get_settings()
    
    if platform_settings.vapid_public_key and platform_settings.vapid_private_key:
        return {
            'public_key': platform_settings.vapid_public_key.strip(),
            'private_key': platform_settings.vapid_private_key.strip(),
            'admin_email': platform_settings.vapid_admin_email or 'admin@azmed.com'
        }

    # Generate new P-256 VAPID keypair
    vapid = Vapid()
    vapid.generate_keys()

    raw_pub = vapid.public_key.public_bytes(
        encoding=serialization.Encoding.X962,
        format=serialization.PublicFormat.UncompressedPoint
    )
    public_key_b64 = base64.urlsafe_b64encode(raw_pub).decode('utf-8').rstrip('=')

    private_key_pem = vapid.private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption()
    ).decode('utf-8')

    platform_settings.vapid_public_key = public_key_b64
    platform_settings.vapid_private_key = private_key_pem
    if not platform_settings.vapid_admin_email:
        platform_settings.vapid_admin_email = 'admin@azmed.com'
    platform_settings.save(update_fields=['vapid_public_key', 'vapid_private_key', 'vapid_admin_email'])

    logger.info("Generated new VAPID WebPush keypair for PlatformSettings.")
    return {
        'public_key': public_key_b64,
        'private_key': private_key_pem,
        'admin_email': platform_settings.vapid_admin_email
    }


def send_web_push(subscription, payload_dict):
    """
    Sends an encrypted RFC 8291/8292 Web Push notification to a single PushSubscription.
    Deactivates subscription if endpoint has expired or unsubscribed (HTTP 404 / 410).
    """
    keys = get_or_create_vapid_keys()
    
    subscription_info = {
        "endpoint": subscription.endpoint,
        "keys": {
            "p256dh": subscription.p256dh,
            "auth": subscription.auth
        }
    }

    vapid_claims = {
        "sub": f"mailto:{keys['admin_email']}"
    }

    try:
        webpush(
            subscription_info=subscription_info,
            data=json.dumps(payload_dict),
            vapid_private_key=keys['private_key'],
            vapid_claims=vapid_claims,
            timeout=8
        )
        logger.info(f"Successfully sent WebPush notification to {subscription.user.username}")
        return True
    except WebPushException as ex:
        logger.warning(f"WebPush failed for user {subscription.user.username}: {ex}")
        response = getattr(ex, 'response', None)
        if response is not None and response.status_code in (404, 410):
            logger.info(f"Push endpoint expired (HTTP {response.status_code}). Deactivating subscription {subscription.id}.")
            subscription.is_active = False
            subscription.save(update_fields=['is_active'])
        return False
    except Exception as e:
        logger.error(f"Unexpected error sending WebPush to {subscription.user.username}: {e}")
        return False


def notify_store_admin_new_bill(invoice):
    """
    Dispatches a real-time Web Push notification to all active store admin devices for this store.
    Runs asynchronously in a background thread so POS response is instantaneous.
    """
    if not invoice or not invoice.store:
        return

    def _worker():
        from django.db import connection
        try:
            # Query all active push subscriptions for Store Admins of this store (exclude creator)
            subscriptions = PushSubscription.objects.filter(
                store=invoice.store,
                user__role='STORE_ADMIN',
                is_active=True
            ).exclude(user=invoice.created_by).select_related('user', 'store')

            if not subscriptions.exists():
                return

            staff_name = invoice.created_by.get_full_name() or invoice.created_by.username if invoice.created_by else 'Staff'
            currency = invoice.store.currency or '₹'
            amount_str = f"{currency}{invoice.total_amount:.2f}"

            payload = {
                "title": f"💰 New Sale: {amount_str}",
                "body": f"Invoice #{invoice.invoice_number} generated by {staff_name}.",
                "icon": "/static/images/icon-192.png",
                "badge": "/static/images/badge-72.png",
                "tag": f"bill-{invoice.id}",
                "vibrate": [100, 50, 100, 50, 200],
                "data": {
                    "invoice_id": invoice.id,
                    "invoice_number": invoice.invoice_number,
                    "amount": str(invoice.total_amount),
                    "staff_name": staff_name,
                    "url": f"/billing/invoices/{invoice.id}/"
                }
            }

            for sub in subscriptions:
                send_web_push(sub, payload)
        except Exception as e:
            logger.error(f"Error in notify_store_admin_new_bill worker: {e}")
        finally:
            connection.close()

    thread = threading.Thread(target=_worker, daemon=True)
    thread.start()
